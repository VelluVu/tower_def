#!/usr/bin/env python3
"""Draws the backgrounds of the boss intro cards.

    python tools/art/boss_cards.py [--preview <dir>]

Writes assets/art/ui/boss_cards/boss_card_<boss>.txt/.aseprite/.png (150x48, drawn at 2x): a dark frame in the
boss's area colours with horn tips on the top corners, a glowing portrait window on the left (BossIntro puts
the boss's own walk animation there at 2x) and streaks running right behind the name. Edit and rerun.
"""
import math
import os
import sys
from pathlib import Path

from PIL import Image

import hoard_backdrop as hb

ROOT = Path(__file__).resolve().parents[2]
hb.ART = ROOT / "assets" / "art" / "ui" / "boss_cards"
CW, CH = 150, 48
WINDOW = (2, 2, 46, 46)        # the portrait window, inside the frame
GLOW_AT = (24, 26)

# per boss: dark .. light ramp of its area, and its accent (the window's rim and the divider)
RAMPS = {
    "broodmother": (["181425", "2a1a33", "45254f", "68386c", "8e4f7a"], "b55088"),
    "bog_hydra": (["101c1c", "17323a", "1f5048", "2d7356", "4a9a5c"], "8fc46a"),
    "dragonslayer": (["1c1214", "3e2731", "5d1d2c", "8b2330", "be4a2f"], "feae34"),
    "bone_colossus": (["1e1a1a", "3a3030", "6b5a4a", "b86f50", "e4a672"], "ead4aa"),
    "magma_titan": (["1a0f12", "3e2731", "733e39", "be4a2f", "f77622"], "fee761"),
    "ashen_wyrm": (["121018", "262b44", "3c3b4c", "5a6988", "8b9bb4"], "f77622"),
}
OUTLINE = "181425"
HORN = ["c0cbdc", "e8e0d0"]


def card(boss):
    ramp, accent = RAMPS[boss]
    keys = []
    for i, h in enumerate(ramp):
        hb.C["%s%d" % (boss, i)] = h
        keys.append("%s%d" % (boss, i))
    for k in (accent, OUTLINE) + tuple(HORN):
        hb.C[k] = k
    cv = hb.Canvas(CW, CH)
    # the body: dark, a little lighter towards the window, with streaks running right
    for y in range(CH):
        for x in range(CW):
            streak = (x - 3 * y) % 31 == 0 and x > 52
            cv.put(x, y, keys[0] if streak else keys[2 if x < 50 else 1])
    # the portrait window: rings of glow around the boss
    x0, y0, x1, y1 = WINDOW
    for y in range(y0, y1):
        for x in range(x0, x1):
            d = math.hypot(x + 0.5 - GLOW_AT[0], (y + 0.5 - GLOW_AT[1]) * 1.1)
            step = 4 if d < 9 else (3 if d < 15 else (2 if d < 21 else 1))
            cv.put(x, y, keys[step])
    for x in range(x0, x1):
        cv.put(x, y1, accent)
    for y in range(y0, y1 + 1):
        cv.put(x1, y, accent)
    # a line under the name and the outer frame
    for x in range(54, CW - 6):
        if x % 2 == 0 or x < 100:
            cv.put(x, 27, keys[3])
    for x in range(CW):
        cv.put(x, 0, OUTLINE)
        cv.put(x, CH - 1, OUTLINE)
        cv.put(x, 1, keys[3])
    for y in range(CH):
        cv.put(0, y, OUTLINE)
        cv.put(CW - 1, y, OUTLINE)
        cv.put(1, y, keys[3])
    # horn tips on the top corners, as the theme's horn panels
    for cx, side in ((3, 1), (CW - 4, -1)):
        for x, y, k in ((cx, 3, HORN[0]), (cx, 2, HORN[0]), (cx + side, 2, HORN[1]), (cx + side, 1, HORN[1]),
                        (cx + 2 * side, 1, HORN[1]), (cx + 2 * side, 0, HORN[1]), (cx + 3 * side, 0, HORN[1])):
            cv.put(x, y, k)
    return cv


def main(argv):
    pictures = {boss: card(boss) for boss in RAMPS}
    if "--preview" in argv:
        out = argv[argv.index("--preview") + 1]
        sheet = Image.new("RGBA", (CW * 2 + 4, (CH + 4) * 3), (0x5a, 0x69, 0x88, 255))
        for i, boss in enumerate(RAMPS):
            sheet.alpha_composite(pictures[boss].image(), ((i % 2) * (CW + 4), (i // 2) * (CH + 4)))
        sheet.resize((sheet.width * 4, sheet.height * 4), Image.NEAREST).save(os.path.join(out, "boss_cards.png"))
        return 0
    hb.ART.mkdir(parents=True, exist_ok=True)
    note = "Generated by tools/art/boss_cards.py for the boss intro cards; edit that and rerun."
    for boss, cv in pictures.items():
        hb.build("boss_card_" + boss, [cv], (CW, CH), [("IDLE", 100, 1)], note)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
