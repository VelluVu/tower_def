#!/usr/bin/env python3
"""Draws Puffe's portrait moods over his neutral portrait (assets/art/ui/puffe_portrait.png).

    python tools/art/puffe_moods.py [--preview <dir>]

Writes assets/art/ui/puffe_moods/puffe_portrait_<mood>.txt/.aseprite/.png for happy, worried, angry and
smug. Each mood repaints only a few pixels of the face (eyes, brows, mouth) and adds one small sign (blush,
a sweat drop, steam, a glint), so he stays the same drakeling. The neutral face is the hand-made original;
rerun this after it changes. PuffeDialogue picks the picture by each PuffeLine's mood.
"""
import os
import sys
from pathlib import Path

from PIL import Image

import hoard_backdrop as hb

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "assets" / "art" / "ui" / "puffe_portrait.png"
hb.ART = ROOT / "assets" / "art" / "ui" / "puffe_moods"

DARK = "107338"     # his eye and brow colour
SHADE = "0b9b55"
LID = "06c374"
WHITE = "ffffff"
BLUSH = "f6757a"
MOUTH = "e43b44"
SWEAT = "2ce8f5"
STEAM = "c0cbdc"
GLINT = "fee761"
CLEAR = None

# (x, y, colour) over the neutral face; eyes are white+dark at (7,6)-(8,6) and (10,6)-(11,6)
MOODS = {
    # eyes squeezed shut in a smile, cheeks flushed, mouth open
    "happy": [(7, 6, DARK), (8, 6, DARK), (10, 6, DARK), (11, 6, DARK), (7, 5, LID), (11, 5, LID),
              (6, 7, BLUSH), (12, 7, BLUSH), (8, 8, DARK), (9, 8, MOUTH), (10, 8, DARK)],
    # brows up in the middle, eyes wide, a small flat mouth and a sweat drop
    "worried": [(7, 5, SHADE), (8, 4, SHADE), (10, 4, SHADE), (11, 5, SHADE), (7, 6, WHITE), (8, 6, DARK),
                (8, 8, SHADE), (9, 8, DARK), (10, 8, SHADE), (13, 4, SWEAT), (13, 5, WHITE)],
    # brows down to the middle, bared teeth, steam off the horns
    "angry": [(7, 4, DARK), (8, 5, DARK), (10, 5, DARK), (11, 4, DARK), (8, 8, DARK), (9, 8, WHITE),
              (10, 8, DARK), (6, 7, MOUTH), (12, 7, MOUTH), (4, 2, STEAM), (5, 1, STEAM), (13, 1, STEAM),
              (12, 2, STEAM)],
    # heavy lids over the pupils, a lopsided smirk and a glint off a horn
    "smug": [(7, 6, LID), (10, 6, LID), (7, 5, SHADE), (8, 5, SHADE), (10, 5, SHADE), (11, 5, SHADE),
             (9, 8, DARK), (10, 8, DARK), (11, 7, DARK), (12, 1, GLINT), (11, 2, CLEAR), (13, 2, GLINT)],
}


def load_base():
    im = Image.open(BASE).convert("RGBA")
    cv = hb.Canvas(im.width, im.height)
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = im.getpixel((x, y))
            if a:
                key = "%02x%02x%02x" % (r, g, b)
                hb.C[key] = key
                cv.px[y][x] = key
    return cv


def mood_canvas(name):
    cv = load_base()
    for x, y, colour in MOODS[name]:
        if colour is None:
            continue
        hb.C[colour] = colour
        cv.px[y][x] = colour
    return cv


def main(argv):
    names = list(MOODS)
    if "--preview" in argv:
        out = argv[argv.index("--preview") + 1]
        base = load_base()
        canvases = [base] + [mood_canvas(n) for n in names]
        sheet = Image.new("RGBA", (len(canvases) * 20, 18), (0x26, 0x2b, 0x44, 255))
        for i, cv in enumerate(canvases):
            sheet.alpha_composite(cv.image(), (i * 20, 0))
        sheet.resize((sheet.width * 12, sheet.height * 12), Image.NEAREST).save(os.path.join(out, "puffe_moods.png"))
        return 0
    hb.ART.mkdir(parents=True, exist_ok=True)
    note = "Generated by tools/art/puffe_moods.py from puffe_portrait.png; edit that and rerun."
    for name in names:
        cv = mood_canvas(name)
        hb.build("puffe_portrait_" + name, [cv], (cv.w, cv.h), [("IDLE", 100, 1)], note)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
