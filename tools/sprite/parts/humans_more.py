def k_sword(hand, tip):
    def draw(f, x, y):
        hx, hy = hand[0] + x, hand[1] + y
        line(f, hx, hy, tip[0] + x, tip[1] + y, 'A')
        f.px[(hx, hy)] = 'm'
        # the cross guard sits one step from the hand towards the tip
        gx = hx + (1 if tip[0] > hand[0] else -1 if tip[0] < hand[0] else 0)
        gy = hy + (1 if tip[1] > hand[1] else -1 if tip[1] < hand[1] else 0)
        if gx == hx:
            f.px[(gx - 1, gy)] = 'g'
            f.px[(gx + 1, gy)] = 'g'
        else:
            f.px[(gx, gy - 1)] = 'g'
            f.px[(gx, gy + 1)] = 'g'
        f.px[(gx, gy)] = 'G'
        f.px[(hx, hy + 1)] = 'B'
    return draw


# everything above the hips sits this much lower than the first draft: short, sturdy legs (5 rows, not 7)
K_BODY_DROP = 2


def k_leg(f, hx, hy, off, col, boot, feet, lift=0, width=2, shade=None):
    """A plate leg: stiff, it swings from the hip as one straight greave (limbs.leg bends it on the way down,
    which on a 5-row leg reads as a knee)."""
    foot = feet - lift
    for y in range(hy, foot + 1):
        x = hx if y == hy else hx + off
        for w in range(width):
            c = boot if y >= foot - (width - 1) else (shade if (shade and w == width - 1) else col)
            f.px[(x + w, y)] = c
    f.px[(hx + off + width, foot)] = boot


def knight(x=0, y=0, legs=(0, 0), lift=(0, 0), sword=None, shield_dx=0, head_dx=0):
    f = Frame(26, 26)
    body_y = y + K_BODY_DROP
    k_leg(f, 9 + x, 16 + body_y, legs[1], 'C', 'D', K_FEET, lift[1], 2, 'D')
    if sword and sword[2] == 'back':
        k_sword(sword[0], sword[1])(f, x, body_y)
    f.stamp(K_TORSO, 7 + x, 10 + body_y)
    f.stamp(K_HELM, 8 + x + head_dx, 3 + body_y)
    k_leg(f, 12 + x, 16 + body_y, legs[0], 'B', 'D', K_FEET, lift[0], 2, 'C')
    if sword and sword[2] == 'front':
        k_sword(sword[0], sword[1])(f, x, body_y)
    f.stamp(K_SHIELD, 14 + x + shield_dx, 11 + body_y)
    return f


