FEET = 15


class Human:
    def __init__(self, head, torso, far_arm, legs_col, far_col, boot, hip_y, back=None):
        self.head, self.torso, self.far_arm, self.back = head, torso, far_arm, back
        self.legs_col, self.far_col, self.boot, self.hip_y = legs_col, far_col, boot, hip_y

    def frame(self, x=0, y=0, legs=(0, 0), lift=(0, 0), head_dx=0, extra=None, behind=None):
        f = Frame(18, 18)
        if behind:
            behind(f, x, y)
        if self.back:
            f.stamp(self.back, 3 + x, 7 + y)
        leg(f, 7 + x, self.hip_y + y, legs[1], self.far_col, self.boot, FEET, lift[1])
        if self.far_arm:
            f.stamp(self.far_arm, 5 + x, 8 + y)
        f.stamp(self.torso, 5 + x, 7 + y)
        f.stamp(self.head, 5 + x + head_dx, 1 + y)
        leg(f, 9 + x, self.hip_y + y, legs[0], self.legs_col, self.boot, FEET, lift[0])
        if extra:
            extra(f, x, y)
        return f


def walk(h, extra_for, n=4, head_dx=0, bob=-1):
    seq = [(2, -1, 0, 0, 0), (0, 0, 0, 1, bob), (-1, 2, 0, 0, 0), (0, 0, 1, 0, bob)][:n]
    return [h.frame(legs=(a, b), lift=(la, lb), y=dy, head_dx=head_dx, extra=extra_for(dy)) for a, b, la, lb, dy in seq]


