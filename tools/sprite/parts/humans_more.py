def staff(raise_=0, glow=0, dy=0):
    def draw(f, x, y):
        sx = 12 + x + (1 if raise_ else 0)
        top = 4 + y + dy - raise_
        for yy in range(top + 1, 15 + y - raise_):
            f.px[(sx, yy)] = 'l'
        f.px[(sx, top)] = 'b'
        f.px[(sx, top - 1)] = 'c'
        f.px[(sx + 1, top - 1)] = 'b'
        f.px[(sx + 1, top)] = 'b' if not glow else 'c'
        if glow >= 1:
            f.px[(sx, top - 1)] = 'w'
            f.px[(sx - 1, top - 1)] = 'c'
            f.px[(sx + 2, top - 1)] = 'c'
            f.px[(sx, top - 2)] = 'c'
            f.px[(sx + 1, top - 2)] = 'c'
        if glow >= 2:
            f.px[(sx + 2, top - 2)] = 'y'
            f.px[(sx - 1, top - 2)] = 'y'
            f.px[(sx + 3, top - 1)] = 'y'
        f.px[(sx - 1, 9 + y + dy - raise_)] = 's'
        f.px[(sx - 1, 10 + y + dy - raise_)] = 'q'
    return draw


