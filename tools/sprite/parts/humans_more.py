def bow(pull=0, arrow=False, dy=0, bx=13):
    def draw(f, x, y):
        top, bot = 4 + y + dy, 12 + y + dy
        mid = 8 + y + dy
        f.px[(bx - 1 + x, top)] = 'm'
        for yy in range(top + 1, bot):
            f.px[(bx + x + (1 if top + 2 <= yy <= bot - 2 else 0), yy)] = 'l'
        f.px[(bx - 1 + x, bot)] = 'm'
        sx = bx - 1 + x - pull
        line(f, bx - 1 + x, top + 1, sx, mid, 'A')
        line(f, sx, mid, bx - 1 + x, bot - 1, 'A')
        f.px[(sx, mid)] = 't'
        if arrow:
            line(f, sx + 1, mid, bx + 2 + x, mid, "l")
            f.px[(bx + 3 + x, mid)] = "A"
        f.px[(bx + 1 + x, mid)] = 't'
    return draw


