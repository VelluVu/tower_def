"""Area props: cave decor, the swamp's sinking human ruins and the human lands' farm props.
One tag per prop (one frame each), 1 px clear around every prop. Light from the top left, no black outlines.
usage: area_props.py <parts dir> <tiles dir>   (tiles dir = assets/art/tiles)"""
import sys
sys.path.insert(0, sys.argv[1])
from compose import Frame, part, write_spec

TILES = sys.argv[2]


def sheet(path, header, pal, size, props):
    tags = []
    for name, art in props:
        f = Frame(*size)
        p = part(art)
        h = max(y for _, y, _ in p) + 1
        w = max(x for x, _, _ in p) + 1
        # bottom-centred: props stand on the bottom of their cell
        f.stamp(p, (size[0] - w) // 2, size[1] - 1 - h)
        tags.append((name, 100, [f]))
    write_spec(path, header, pal, size, tags)


