def horse_leg(f, hx, hy, dx, lift, col):
    foot = 23 - lift * 2
    knee = (hx + (dx // 2), hy + 3 - lift)
    line(f, hx, hy, knee[0], knee[1], col)
    line(f, knee[0], knee[1], hx + dx, foot - 1, col)
    f.px[(hx + dx, foot)] = 'o'
    f.px[(hx + dx + 1, foot)] = 'o'


def lance(level, reach=0):
    def draw(f, x, y):
        if level:
            line(f, 5 + x, 9 + y, 21 + reach + x, 9 + y, 'l')
            f.px[(22 + reach + x, 9 + y)] = 'A'
            f.px[(23 + reach + x, 9 + y)] = 'B' if reach < 0 else 'A'
        else:
            line(f, 9 + x, 13 + y, 20 + x, 3 + y, 'l')
            f.px[(21 + x, 2 + y)] = 'A'
            f.px[(20 + x, 2 + y)] = 'r'
            f.px[(21 + x, 3 + y)] = 'r'
        f.px[(14 + x, 10 + y)] = 't'
    return draw


def cavalry(gait=0, y=0, level=False, reach=0, x=0):
    f = Frame(26, 26)
    legs = GAITS[gait]
    horse_leg(f, 8 + x, 17 + y, legs[1][0], legs[1][1], 'm')
    horse_leg(f, 17 + x, 17 + y, legs[3][0], legs[3][1], 'm')
    f.stamp(TAIL, 2 + x, 12 + y)
    f.stamp(HORSE, 4 + x, 12 + y)
    f.stamp(NECK, 15 + x, 6 + y)
    horse_leg(f, 6 + x, 17 + y, legs[0][0], legs[0][1], 'l')
    horse_leg(f, 15 + x, 17 + y, legs[2][0], legs[2][1], 'l')
    f.stamp(BLANKET, 8 + x, 11 + y)
    f.stamp(RIDER, 9 + x, 2 + y)
    lance(level, reach)(f, x, y)
    return f


