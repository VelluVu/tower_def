def wing(f, tip, shoulder=(13, 11)):
    sx, sy = shoulder
    cols = ['l', 'l', 'm', 'm', 'o', 'o']
    for k, c in enumerate(cols):
        line(f, sx - k, sy, tip[0] - k, tip[1] + (k // 2 if tip[1] < sy else -(k // 2)), c)


def talons(f, x, y, open_=False):
    f.px[(12 + x, 14 + y)] = 'g'
    f.px[(13 + x, 14 + y)] = 'g'
    if open_:
        f.px[(14 + x, 15 + y)] = 'g'
        f.px[(11 + x, 15 + y)] = 'g'
    else:
        f.px[(12 + x, 15 + y)] = 'G'
        f.px[(13 + x, 15 + y)] = 'G'


def eagle(tip, y=0, x=0, open_=False, far_tip=None):
    f = Frame(24, 24)
    if far_tip:
        wing(f, (far_tip[0] + x, far_tip[1] + y), (14 + x, 11 + y))
        for p in list(f.px):
            f.px[p] = 'o' if f.px[p] != 'o' else 'o'
    f.stamp(EAGLE, 2 + x, 10 + y)
    talons(f, x, y, open_)
    wing(f, (tip[0] + x, tip[1] + y), (13 + x, 11 + y))
    return f


