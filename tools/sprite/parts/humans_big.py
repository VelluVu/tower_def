def greatsword(hand, tip, f, wide=True):
    line(f, hand[0], hand[1], tip[0], tip[1], 'A')
    if wide:
        dx = 1 if abs(tip[1] - hand[1]) >= abs(tip[0] - hand[0]) else 0
        line(f, hand[0] + dx, hand[1] + (1 - dx), tip[0] + dx, tip[1] + (1 - dx), 'B')
    f.px[(hand[0], hand[1])] = 'm'
    f.px[(hand[0] + 1, hand[1])] = 'g'
    f.px[(hand[0] - 1, hand[1])] = 'g'


def slayer(x=0, y=0, legs=(0, 0), lift=(0, 0), sword=((22, 22), (30, 5)), cape=0, head_dx=0, behind=False, crouch=0):
    f = Frame(40, 40)
    f.stamp(D_CAPE, 9 + x - cape, 15 + y + crouch)
    hip = 24 + y + crouch
    leg(f, 15 + x, hip, legs[1], 'D', 'E', D_FEET, lift[1], 3, 'E')
    if behind and sword:
        greatsword((sword[0][0] + x, sword[0][1] + y), (sword[1][0] + x, sword[1][1] + y), f)
    f.stamp(D_TORSO, 12 + x, 13 + y + crouch)
    f.stamp(D_HELM, 13 + x + head_dx, 4 + y + crouch)
    leg(f, 19 + x, hip, legs[0], 'B', 'E', D_FEET, lift[0], 3, 'C')
    if sword and not behind:
        greatsword((sword[0][0] + x, sword[0][1] + y + crouch), (sword[1][0] + x, sword[1][1] + y + crouch), f)
    # gauntlets on the hilt
    if sword:
        f.px[(sword[0][0] + x, sword[0][1] + 1 + y + crouch)] = 'C'
    return f


